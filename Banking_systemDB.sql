-- Solve above questions using JOINTS

SELECT B.BRANCHID, B.BRANCHNAME, SUM(L.LOANAMOUNT) AS TOTAL_LOAN_EXPOSURE
FROM BRANCHES B
INNER JOIN ACCOUNTS A
    ON B.BRANCHID = A.BRANCHID
INNER JOIN LOANS L
    ON A.CUSTOMERID = L.CUSTOMERID
GROUP BY B.BRANCHID, B.BRANCHNAME
ORDER BY TOTAL_LOAN_EXPOSURE DESC LIMIT 1;

